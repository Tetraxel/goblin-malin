import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import prettier from "prettier";
import { EXTENSION_API_VERSION } from "../src/constants";

/**
 * The shape of the extension API (P34, T34.1): `api/types.ts` printed without its comments, plus the API version.
 * Committed as `docs/extension-api.snapshot.d.ts`; a unit test fails when the two differ, so a change of the public
 * types is always a decision (refresh with `yarn run extension-api --write`, and bump `EXTENSION_API_VERSION` when
 * it breaks extensions written for the current one). Used by `scripts/extension-api.ts` and the test, never by the app.
 */
const here = path.dirname(fileURLToPath(import.meta.url));
export const API_TYPES_PATH = path.join(here, "../src/extensions/api/types.ts");
export const API_SNAPSHOT_PATH = path.join(here, "../docs/extension-api.snapshot.d.ts");

export async function currentApiShape(): Promise<string> {
    const text = await fs.readFile(API_TYPES_PATH, "utf-8");
    const source = ts.createSourceFile("types.ts", text, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TS);
    const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });
    // Printed from the syntax tree, then formatted: neither the comments nor the layout of types.ts count.
    const printed = printer.printFile(source).replace(/\s+/g, " ");
    const body = (
        await prettier.format(printed, { parser: "typescript", printWidth: 120, tabWidth: 4, trailingComma: "es5" })
    ).trim();
    return (
        `// Generated by \`yarn run extension-api --write\` from src/extensions/api/types.ts. Do not edit.\n` +
        `// Extension API version: ${EXTENSION_API_VERSION}\n\n${body}\n`
    );
}

export async function committedApiShape(): Promise<string | undefined> {
    return fs.readFile(API_SNAPSHOT_PATH, "utf-8").catch(() => undefined);
}
